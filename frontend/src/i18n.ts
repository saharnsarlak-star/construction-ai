export function t(lang: LanguageCode, key: string): string {
  return dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
}

/** Map stored impact tags (any language) to the current UI language. */
export function displayImpact(raw: string | null | undefined, lang: LanguageCode): string {
  if (!raw) return "";
  const k = raw.trim().toLowerCase();
  const map: Record<string, "high" | "medium" | "low"> = {
    high: "high",
    بالا: "high",
    hoch: "high",
    "élevé": "high",
    eleve: "high",
    medium: "medium",
    متوسط: "medium",
    mittel: "medium",
    moyen: "medium",
    low: "low",
    پایین: "low",
    niedrig: "low",
    faible: "low",
  };
  const key = map[k];
  return key ? t(lang, key) : raw;
}

