def localized_seed_fields(code: str, title_en: str, description_en: str) -> tuple[LangMap, LangMap, LangMap]:
    entry = SEED_I18N.get(code, {})
    title = _L(
        entry.get("title_fa", title_en),
        title_en,
        entry.get("title_de", title_en),
        entry.get("title_fr", title_en),
    )
    description = _L(
        entry.get("desc_fa", description_en),
        description_en,
        entry.get("desc_de", description_en),
        entry.get("desc_fr", description_en),
    )
    recommendation = _L(
        entry.get("rec_fa", _DEFAULT_REC[LanguageCode.FA]),
        entry.get("rec_en", _DEFAULT_REC[LanguageCode.EN]),
        entry.get("rec_de", _DEFAULT_REC[LanguageCode.DE]),
        entry.get("rec_fr", _DEFAULT_REC[LanguageCode.FR]),
    )
    return title, description, recommendation
